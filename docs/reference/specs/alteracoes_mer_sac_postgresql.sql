ALTER TABLE public.contrato
    ADD COLUMN IF NOT EXISTS unidade_responsavel_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contrato_unidade_responsavel') THEN
        ALTER TABLE public.contrato
            ADD CONSTRAINT fk_contrato_unidade_responsavel
            FOREIGN KEY (unidade_responsavel_id)
            REFERENCES sac_gestao.unidade_organizacional(id);
    END IF;
END $$;

