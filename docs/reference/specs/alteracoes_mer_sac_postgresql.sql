/*
 ETICE - Evolucao do MER do SAC
 Banco alvo: PostgreSQL 14 ou superior

 Escopo: dados organizacionais, contratuais, financeiros, renovacoes,
 riscos administrativos, planos de acao e gestao comercial.

 Fora do escopo: KPIs tecnicos, SLA, avaliacao da qualidade da execucao
 e calculo detalhado de glosas. Esses dados pertencem ao Projeto de KPIs.

 IMPORTANTE
 1. Executar primeiro em homologacao e com backup validado.
 2. Conferir nomes, schemas, tipos das PKs e volume das tabelas existentes.
 3. O script preserva campos legados e cria um schema complementar.
 4. As operacoes de UPDATE para UUID podem ser executadas em lotes em bases grandes.
*/

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS sac_gestao;

-- ---------------------------------------------------------------------------
-- 0. Validacao minima do modelo existente
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    tabela text;
BEGIN
    FOREACH tabela IN ARRAY ARRAY[
        'public.contrato', 'public.contrato_item', 'public.ordem_servico',
        'public.cliente', 'public.fornecedor', 'public.usuario',
        'public.servico', 'public.documento', 'public.aditivo',
        'public.ciclo_faturamento'
    ]
    LOOP
        IF to_regclass(tabela) IS NULL THEN
            RAISE EXCEPTION 'Tabela obrigatoria nao encontrada: %', tabela;
        END IF;
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 1. Identificadores estaveis para integracao com o Projeto de KPIs
-- ---------------------------------------------------------------------------
ALTER TABLE public.contrato      ADD COLUMN IF NOT EXISTS uuid_integracao uuid;
ALTER TABLE public.contrato_item ADD COLUMN IF NOT EXISTS uuid_integracao uuid;
ALTER TABLE public.ordem_servico ADD COLUMN IF NOT EXISTS uuid_integracao uuid;
ALTER TABLE public.cliente       ADD COLUMN IF NOT EXISTS uuid_integracao uuid;
ALTER TABLE public.fornecedor    ADD COLUMN IF NOT EXISTS uuid_integracao uuid;
ALTER TABLE public.servico       ADD COLUMN IF NOT EXISTS uuid_integracao uuid;

UPDATE public.contrato      SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;
UPDATE public.contrato_item SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;
UPDATE public.ordem_servico SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;
UPDATE public.cliente       SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;
UPDATE public.fornecedor    SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;
UPDATE public.servico       SET uuid_integracao = gen_random_uuid() WHERE uuid_integracao IS NULL;

ALTER TABLE public.contrato      ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();
ALTER TABLE public.contrato_item ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();
ALTER TABLE public.ordem_servico ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();
ALTER TABLE public.cliente       ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();
ALTER TABLE public.fornecedor    ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();
ALTER TABLE public.servico       ALTER COLUMN uuid_integracao SET DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS ux_contrato_uuid_integracao
    ON public.contrato(uuid_integracao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_contrato_item_uuid_integracao
    ON public.contrato_item(uuid_integracao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ordem_servico_uuid_integracao
    ON public.ordem_servico(uuid_integracao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_cliente_uuid_integracao
    ON public.cliente(uuid_integracao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_fornecedor_uuid_integracao
    ON public.fornecedor(uuid_integracao);
CREATE UNIQUE INDEX IF NOT EXISTS ux_servico_uuid_integracao
    ON public.servico(uuid_integracao);

