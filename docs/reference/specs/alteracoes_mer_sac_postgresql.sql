CREATE OR REPLACE VIEW sac_gestao.vw_saldo_item_contrato AS
WITH mov AS (
    SELECT
        contrato_item_id,
        SUM(CASE WHEN tipo_movimento IN ('ADITIVO','AJUSTE_CONTRATUAL')
                 THEN valor ELSE 0 END) AS valor_aditivos_ajustes,
        SUM(CASE WHEN tipo_movimento='ORDEM_SERVICO' THEN valor
                 WHEN tipo_movimento='CANCELAMENTO_OS' THEN -valor ELSE 0 END) AS comprometido_os,
        SUM(CASE WHEN tipo_movimento='MEDICAO' THEN valor
                 WHEN tipo_movimento='ESTORNO_MEDICAO' THEN -valor ELSE 0 END) AS medido,
        SUM(CASE WHEN tipo_movimento='PAGAMENTO' THEN valor
                 WHEN tipo_movimento='ESTORNO_PAGAMENTO' THEN -valor ELSE 0 END) AS pago
    FROM sac_gestao.movimento_contrato_item
    GROUP BY contrato_item_id
), calc AS (
    SELECT
        ci.id AS contrato_item_id,
        ci.contrato_id,
        ci.seq,
        ci.especificacao,
        ci.valor_total AS valor_contratado,
        ci.valor_total + COALESCE(m.valor_aditivos_ajustes,0) AS valor_vigente,
        COALESCE(m.comprometido_os,0) AS valor_comprometido_os,
        COALESCE(m.medido,0) AS valor_medido,
        COALESCE(m.pago,0) AS valor_pago
    FROM public.contrato_item ci
    LEFT JOIN mov m ON m.contrato_item_id = ci.id
)
SELECT
    c.*,
    c.valor_vigente - c.valor_comprometido_os AS saldo_disponivel_os,
    c.valor_vigente - c.valor_medido AS saldo_a_executar,
    c.valor_medido - c.valor_pago AS saldo_a_pagar,
    CASE WHEN c.valor_vigente > 0
         THEN ROUND(((c.valor_vigente-c.valor_medido)/c.valor_vigente)*100,2)
         ELSE 0 END AS percentual_saldo_a_executar,
    CASE
        WHEN c.valor_vigente <= 0 THEN 'VERMELHO'
        WHEN ((c.valor_vigente-c.valor_medido)/c.valor_vigente)*100 >= 60 THEN 'VERDE'
        WHEN ((c.valor_vigente-c.valor_medido)/c.valor_vigente)*100 <= 10 THEN 'VERMELHO'
        ELSE 'AMARELO'
    END AS faixa_saldo
FROM calc c;

CREATE OR REPLACE VIEW sac_gestao.vw_aging_financeiro AS
SELECT
    df.contrato_id,
    df.cliente_id,
    df.fornecedor_id,
    df.id AS documento_financeiro_id,
    df.numero,
    df.data_emissao,
    df.data_vencimento,
    COALESCE(df.valor_liquido, df.valor_bruto) AS valor_documento,
    COALESCE(SUM(tf.valor) FILTER (WHERE tf.status='REALIZADA' AND tf.tipo IN ('RECEBIMENTO','PAGAMENTO')),0)
        - COALESCE(SUM(tf.valor) FILTER (WHERE tf.status='REALIZADA' AND tf.tipo='ESTORNO'),0) AS valor_realizado,
    COALESCE(df.valor_liquido, df.valor_bruto)
        - COALESCE(SUM(tf.valor) FILTER (WHERE tf.status='REALIZADA' AND tf.tipo IN ('RECEBIMENTO','PAGAMENTO')),0)
        + COALESCE(SUM(tf.valor) FILTER (WHERE tf.status='REALIZADA' AND tf.tipo='ESTORNO'),0) AS valor_em_aberto,
    CASE
        WHEN df.data_vencimento IS NULL OR df.data_vencimento >= CURRENT_DATE THEN 'A_VENCER'
        WHEN CURRENT_DATE-df.data_vencimento <= 15 THEN 'VENCIDO_1_15'
        WHEN CURRENT_DATE-df.data_vencimento <= 30 THEN 'VENCIDO_16_30'
        ELSE 'VENCIDO_MAIS_30'
    END AS faixa_aging
FROM sac_gestao.documento_financeiro df
LEFT JOIN sac_gestao.transacao_financeira tf ON tf.documento_financeiro_id = df.id
GROUP BY df.id;

