DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ciclo_contrato') THEN
        ALTER TABLE public.ciclo_faturamento ADD CONSTRAINT fk_ciclo_contrato
            FOREIGN KEY (contrato_id) REFERENCES public.contrato(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ciclo_cliente') THEN
        ALTER TABLE public.ciclo_faturamento ADD CONSTRAINT fk_ciclo_cliente
            FOREIGN KEY (cliente_id) REFERENCES public.cliente(id);
    END IF;
END $$;

